def get_llm():
    api_key = os.getenv("GROQ_API_KEY")
    if not api_key:
        raise HTTPException(
            status_code=500,
            detail="GROQ_API_KEY environment variable is not set. Please configure it in your settings."
        )
    api_key = api_key.strip("'\" \t\r\n")
    primary_llm = ChatGroq(
        model="groq/compound-mini",
        api_key=api_key,
        temperature=0.0,
    )
    fallback_llm1 = ChatGroq(
        model="groq/compound",
        api_key=api_key,
        temperature=0.0,
    )
    fallback_llm2 = ChatGroq(
        model="qwen/qwen3.6-27b",
        api_key=api_key,
        temperature=0.0,
    )
    fallback_llm3 = ChatGroq(
        model="openai/gpt-oss-20b",
        api_key=api_key,
        temperature=0.0,
    )
    return primary_llm.with_fallbacks([fallback_llm1, fallback_llm2, fallback_llm3])

_embeddings_instance = None

def get_embeddings():
    global _embeddings_instance
    if _embeddings_instance is None:
        api_key = os.getenv("VOYAGE_API_KEY")
        if not api_key:
            raise ValueError(
                "VOYAGE_API_KEY is not set in environment or backend/.env! "
                "Please add your Voyage AI API key."
            )
        model = os.getenv("VOYAGE_MODEL", "voyage-4-large")
        print(f"Using Voyage AI Embeddings (model={model})...")
        _embeddings_instance = VoyageAIEmbeddings(
            voyage_api_key=api_key,
            model=model
        )
    return _embeddings_instance

