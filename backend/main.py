@app.on_event("startup")
async def startup_warmup():
    """Pre-warm the embedding model at startup so the first upload is fast.
    This runs in background — the server starts accepting requests immediately,
    but /health will report ready=false until embeddings are loaded."""
    global _backend_ready
    import asyncio
    loop = asyncio.get_event_loop()
    try:
        print("[startup] Pre-warming embedding model...")
        await loop.run_in_executor(None, get_embeddings)
        print("[startup] Embedding model ready.")
    except Exception as e:
        print(f"[startup] Embedding warmup failed (will retry on first request): {e}")
    _backend_ready = True

