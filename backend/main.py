@app.post("/upload")
@app.post("/api/upload")
async def upload_pdf(
    file: UploadFile = File(...),
    session_id: str = Query(None)
):
    try:
        print("Upload started (session: " + str(session_id) + ")")
        filename = file.filename
        lower_name = filename.lower()
        if not lower_name.endswith(".pdf"):
            raise HTTPException(status_code=400, detail="Only PDF files are supported")

        safe_filename = os.path.basename(filename)
        session_upload_folder = get_session_upload_folder(session_id)
        collection_name = get_collection_name(session_id)

        print("Saving file: " + safe_filename)
        file_path = os.path.join(session_upload_folder, safe_filename)

        with open(file_path, "wb") as buffer:
            shutil.copyfileobj(file.file, buffer)

        import asyncio
        loop = asyncio.get_event_loop()

        def _process_file():
            try:
                qclient = get_qdrant_client()
                qclient.delete_collection(collection_name=collection_name)
                print(f"Cleared existing Qdrant collection: {collection_name}")
            except Exception as e:
                print(f"Note: No existing collection to clear ({e})")

            print("Partitioning PDF")
            elements = partition_document(file_path)

            print("Chunking elements")
            chunks = chunk_document(elements)

            print("Processing chunks")
            processed_documents = process_chunks(chunks, source_name=safe_filename)

            if len(processed_documents) == 0:
                raise ValueError("No usable content could be extracted from this PDF")

            print("Creating vectorstore")
            create_vectorstore(processed_documents, collection_name=collection_name)
            return len(processed_documents)

        chunks_count = await loop.run_in_executor(None, _process_file)

        print("Done")
        return {
            "message": "PDF processed successfully",
            "chunks_indexed": chunks_count
        }

    except HTTPException:
        raise
    except ValueError as e:
        raise HTTPException(status_code=422, detail=str(e))
    except Exception as e:
        traceback.print_exc()
        raise HTTPException(status_code=500, detail=f"Failed to process PDF: {type(e).__name__}: {str(e)}")

@app.post("/chat")
@app.post("/api/chat")
async def chat(
    request: ChatRequest = None,
    question: str = Query(None),
    session_id: str = Query(None)
):
    try:
        q_val = None
        if request and request.question:
            q_val = request.question
        elif question:
            q_val = question

        if not q_val or not q_val.strip():
            raise HTTPException(
                status_code=400,
                detail="Question cannot be empty",
            )
        question = q_val.strip()

        collection_name = get_collection_name(session_id)

        try:
            qclient = get_qdrant_client()
            col_info = qclient.get_collection(collection_name)
            if col_info.points_count == 0:
                raise HTTPException(
                    status_code=400,
                    detail="No document has been ingested yet. Upload a PDF first.",
                )
        except HTTPException:
            raise
        except Exception:
            raise HTTPException(
                status_code=400,
                detail="No document has been ingested yet. Upload a PDF first.",
            )

        vectorstore = QdrantVectorStore.from_existing_collection(
            embedding=get_embeddings(),
            collection_name=collection_name,
            url=os.getenv("QDRANT_URL"),
            api_key=os.getenv("QDRANT_API_KEY"),
        )

        agent = StudyAgent(vectorstore=vectorstore, llm=get_llm())
        result = agent.invoke(question)

        res = {
            "answer": result.get("answer", "No response generated."),
            "sources": result.get("sources", []),
            "steps": result.get("steps", [])
        }
        return res
    except HTTPException:
        raise
    except Exception as e:
        traceback.print_exc()
        raise HTTPException(
            status_code=500,
            detail=f"Chat processing error: {str(e)}"
        )

