from starlette.middleware.base import BaseHTTPMiddleware
from starlette.responses import Response

class CORSOnAllResponses(BaseHTTPMiddleware):
    """Ensures CORS headers are added to ALL responses, including error responses.
    
    FastAPI's built-in CORSMiddleware does NOT add CORS headers to responses
    generated by exception handlers, causing the browser to report CORS errors
    when the backend returns 4xx/5xx (e.g. upload failures).
    """
    async def dispatch(self, request, call_next):
        if request.method == "OPTIONS":
            response = Response(status_code=200)
            response.headers["Access-Control-Allow-Origin"] = "*"
            response.headers["Access-Control-Allow-Methods"] = "GET, POST, PUT, DELETE, OPTIONS"
            response.headers["Access-Control-Allow-Headers"] = "*"
            response.headers["Access-Control-Max-Age"] = "3600"
            return response
        
        response = await call_next(request)
        response.headers["Access-Control-Allow-Origin"] = "*"
        response.headers["Access-Control-Allow-Methods"] = "GET, POST, PUT, DELETE, OPTIONS"
        response.headers["Access-Control-Allow-Headers"] = "*"
        response.headers["Access-Control-Expose-Headers"] = "*"
        return response

app.add_middleware(CORSOnAllResponses)

